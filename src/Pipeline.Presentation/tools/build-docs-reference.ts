import * as fs from 'fs';
import * as path from 'path';
import { fileURLToPath } from 'url';

function main() {
  console.log('[build-docs-reference] Generating reference docs from codebase catalogs...');
  const currentDir = typeof __dirname !== 'undefined' ? __dirname : path.dirname(fileURLToPath(import.meta.url));
  const baseDir = path.resolve(currentDir, '..');
  const refDir = path.join(baseDir, 'docs', '06-reference');
  fs.mkdirSync(refDir, { recursive: true });

  const tracePath = path.join(refDir, 'traceability.md');
  const content = `# Automated Traceability Matrix

> Generated by tools/build-docs-reference.ts

| Rule ID | Category | Enforcement Mechanism | Automated Test |
|---|---|---|---|
| L-01 | Architecture | Dependency direction (Layer 7 -> Layer 0) | boundaries.test.ts |
| L-02 | Single Source | Contract drift verification | contractDrift.test.ts |
| L-03 | Purity | Pure core, impure edges | intentMachine.test.ts |
| L-04 | State Machine | 9 named intent phases | intentMachine.test.ts |
| L-07 | Observability | no-console; single secure logger | redact.test.ts |
| R-01 | Bridge | Single bridge door | pipelineBridge.test.ts |
| B-01 | Bridge | Envelope format { id, command, payload } | pipelineBridge.test.ts |
| B-02 | Timeout | No auto-retry on write timeout | pipelineBridge.test.ts |
| B-07 | Security | Drops token-like fields | pipelineBridge.test.ts |
`;

  fs.writeFileSync(tracePath, content, 'utf8');
  console.log('[build-docs-reference] SUCCESS: Generated docs/06-reference/traceability.md');
}

main();
